-- 1. DROP ALL UNNECESSARY / LEFTOVER TABLES SHOWN IN YOUR SIDEBAR SCREENSHOT:
DROP TABLE IF EXISTS public.audit_log CASCADE;
DROP TABLE IF EXISTS public.events CASCADE;
DROP TABLE IF EXISTS public.findings CASCADE;
DROP TABLE IF EXISTS public.incidents CASCADE;
DROP TABLE IF EXISTS public.origins CASCADE;
DROP TABLE IF EXISTS public.policies CASCADE;
DROP TABLE IF EXISTS public.training_events CASCADE;
DROP TABLE IF EXISTS public.training_users CASCADE;
DROP TABLE IF EXISTS public.tenants CASCADE;
DROP TABLE IF EXISTS public.transactions CASCADE;

-- 2. CREATE WALLET AUDITS SUMMARY TABLE (Stores wallet balance, risk, audit stats)
CREATE TABLE IF NOT EXISTS public.wallet_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_address TEXT NOT NULL,
    investigator TEXT DEFAULT 'investigator@sentinelchain.ai',
    tx_count INT DEFAULT 1,
    total_in_btc NUMERIC DEFAULT 0.0,
    total_out_btc NUMERIC DEFAULT 0.0,
    net_balance_btc NUMERIC DEFAULT 0.0,
    threat_flagged BOOLEAN DEFAULT FALSE,
    risk_score NUMERIC DEFAULT 15.0,
    timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- 3. CREATE WALLET TRANSACTIONS TABLE (Stores actual transactions to continue next time)
CREATE TABLE IF NOT EXISTS public.wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_address TEXT NOT NULL,
    txid TEXT NOT NULL,
    sender TEXT NOT NULL,
    receiver TEXT NOT NULL,
    tx_amount NUMERIC NOT NULL,
    tx_fee NUMERIC DEFAULT 0.0001,
    in_degree INT DEFAULT 1,
    out_degree INT DEFAULT 2,
    hop_velocity NUMERIC DEFAULT 120.0,
    mixing_score NUMERIC DEFAULT 0.0,
    timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- 4. ENABLE ROW LEVEL SECURITY (RLS) & PUBLIC POLICIES
ALTER TABLE public.wallet_audits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.wallet_transactions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all on wallet_audits" ON public.wallet_audits;
CREATE POLICY "Allow all on wallet_audits" ON public.wallet_audits FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all on wallet_transactions" ON public.wallet_transactions;
CREATE POLICY "Allow all on wallet_transactions" ON public.wallet_transactions FOR ALL USING (true) WITH CHECK (true);

